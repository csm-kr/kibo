  await page.locator('.card', { hasText: '보리별 라면' }).click();
  await shot('10-ramen');
  await page.locator('.x').click();
  await page.locator('.del').first().click();
  await shot('11-delete-confirm');
  await page.getByRole('button', { name: '취소' }).click();
  await page.waitForTimeout(2000);
  await shot('12-cart');
  await page.getByRole('button', { name: '주문 확인하기' }).click();
  await shot('13-review');
  await page.getByRole('button', { name: '주문하기' }).click();
