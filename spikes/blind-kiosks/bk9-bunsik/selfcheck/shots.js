  await page.getByRole('button', { name: /담기/ }).click();
  await shot('04-item-error');
  await page.locator('.chip', { hasText: '3단계 보통맛' }).click();
  for (const t of ['삶은 계란', '어묵 추가', '라면 사리', '비엔나 소시지']) await page.locator('.chip', { hasText: t }).click();
  await shot('05-item-max');
  await page.getByRole('button', { name: /담기/ }).click();
  await page.getByRole('button', { name: '김밥' }).click();
