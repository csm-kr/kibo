  await page.getByRole('button', { name: /담기/ }).click();
  await page.getByRole('button', { name: '세트' }).click();
  await shot('07-menu-set');
  await page.locator('.card', { hasText: '보리별 세트' }).click();
  await page.locator('.bigopt', { hasText: '로제 떡볶이' }).click();
  await page.locator('.chip', { hasText: '4단계 매운맛' }).click();
  await shot('08-set-step1');
  await page.getByRole('button', { name: '다음' }).click();
  await page.locator('.bigopt', { hasText: '참치 김밥' }).click();
