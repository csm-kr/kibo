/** "세트 (Set)": a Korean label with its English; anything else as it is. */
export function gloss(label: string): string {
  const en = GLOSSARY[label];
  return en ? `${label} (${en})` : label;
}

export function glossAll(labels: string[]): string[] {
  return labels.map(gloss);
}
